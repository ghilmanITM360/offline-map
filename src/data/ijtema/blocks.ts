const blockAliases = (number: number): string[] => [
  `Block ${number}`,
  `B${number}`,
  `بلاک ${number}`,
  `block ${number}`,
  `block ${numberWords[number]}`,
];

const cloneCorners = (corners: BlockCorners): BlockCorners => ({
  c1: { ...corners.c1 },
  c2: { ...corners.c2 },
  c3: { ...corners.c3 },
  c4: { ...corners.c4 },
});

const polygonFromCorners = (center: Coordinate, corners: BlockCorners): Coordinate[] =>
  [corners.c1, corners.c2, corners.c3, corners.c4]
    .map((point) => ({ ...point }))
    .sort((a, b) => Math.atan2(a.lat - center.lat, a.lng - center.lng) - Math.atan2(b.lat - center.lat, b.lng - center.lng));

const block = (
  number: number,
  center: Coordinate,
  corners: BlockCorners,
  options: Pick<Partial<Block>, 'polygon' | 'status' | 'sourceNotes'> = {},
): Block => {
  const id = `B${number}` as const;
  const copiedCorners = cloneCorners(corners);

  return {
    id,
    number,
    name: {
      en: `Block ${number}`,
      ur: `بلاک ${number}`,
      romanUrdu: `Block ${number}`,
    },
    center,
    corners: copiedCorners,
    entryPoints: cloneCorners(copiedCorners),
    polygon: options.polygon ?? polygonFromCorners(center, copiedCorners),
    aliases: blockAliases(number),
    category: 'block',
    status: options.status ?? 'provided',
    visual: {
      label: `Block ${number}`,
      fillKey: `block-${number}`,
      showLabelByDefault: true,
    },
    ...(options.sourceNotes ? { sourceNotes: options.sourceNotes } : {}),
  };
};

