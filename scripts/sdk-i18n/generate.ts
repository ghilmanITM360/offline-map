// Builds the consumer's translation table. A screen string takes the wording the Ijtema host ALREADY ships when the host has a message whose
// English is word-for-word the same; every other string takes the SDK team's DRAFT wording from ./draft.ts. Every entry is therefore complete
// (English, Urdu, Roman Urdu) and every entry is pending native review. `node --import tsx scripts/sdk-i18n/generate.ts [--check]`; the
// committed output is `examples/expo-consumer/copy/translationTable.ts` and `docs/sdk/client/TRANSLATION_REVIEW.md`.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ENGLISH_NAVIGATION_SCREEN_COPY } from '../../packages/offline-navigation/src/ui/EnglishNavigationCopy';
import { messages } from '../../src/i18n/messages';
import { DRAFT_WORDING } from './draft';

export interface TranslationEntry {
  /** Path into NavigationScreenCopy. */
  key: string;
  /** The SDK's English with `{0}`, `{1}` for the arguments of a function-valued string; null for a plain string. */
  en: string;
  ur: string;
  urLatn: string;
  /** `host:<message key>` for wording the host already ships, `draft` for the SDK team's unreviewed draft. */
  source: string;
}

const ROOT = join(__dirname, '../..');
const TABLE_FILE = join(ROOT, 'examples/expo-consumer/copy/translationTable.ts');
const REVIEW_FILE = join(ROOT, 'docs/sdk/client/TRANSLATION_REVIEW.md');
const en = messages.en as Record<string, string>;
const ur = messages.ur as Record<string, string>;
const lat = messages['ur-Latn'] as Record<string, string>;

const placeholders = (text: string): string[] => [...text.matchAll(/\{([a-zA-Z]+)\}/g)].map((m) => m[1]);
// Compared without placeholder names and case: `Step {step} of {total}` equals `Step {a} of {b}`.
const shape = (text: string): string => text.replace(/\{[a-zA-Z0-9]+\}/g, '{}').trim().toLowerCase();
const sample = (fn: (...args: string[]) => string): string => fn(...Array.from({ length: fn.length }, (_, i) => `{${i}}`));

const flatten = (node: unknown, path: string, out: Array<{ key: string; en: string }>) => {
  for (const [name, value] of Object.entries(node as Record<string, unknown>)) {
    const key = path ? `${path}.${name}` : name;
    if (typeof value === 'string') out.push({ key, en: value });
    else if (typeof value === 'function') out.push({ key, en: sample(value as (...args: string[]) => string) });
    else if (value && typeof value === 'object') flatten(value, key, out);
  }
};

export function buildTable(): TranslationEntry[] {
  const hostByShape = new Map<string, string[]>();
  for (const key of Object.keys(en)) {
    const s = shape(en[key]);
    hostByShape.set(s, [...(hostByShape.get(s) ?? []), key]);
  }
  const rows: Array<{ key: string; en: string }> = [];
  flatten(ENGLISH_NAVIGATION_SCREEN_COPY, '', rows);
  const result = rows.map(({ key, en: english }): TranslationEntry => {
    // Only an unambiguous host wording qualifies: when several host messages share this English and their Urdu differs, the context decides
    // which is right, so the string is left for the owner instead of picking one.
    const candidates = hostByShape.get(shape(english))?.filter((k) => ur[k] && lat[k]) ?? [];
    const source = candidates[0];
    const draft = (): TranslationEntry => {
      const wording = DRAFT_WORDING[key];
      if (!wording) throw new Error(`no host wording and no draft wording for ${key}; add it to scripts/sdk-i18n/draft.ts`);
      return { key, en: english, ur: wording.ur, urLatn: wording.urLatn, source: 'draft' };
    };
    if (!source) return draft();
    // The host names its placeholders; the screen's functions take positional arguments in the same order of appearance.
    const names = placeholders(en[source]);
    const positional = (text: string) => text.replace(/\{([a-zA-Z]+)\}/g, (whole, name: string) => (names.includes(name) ? `{${names.indexOf(name)}}` : whole));
    const same = candidates.every((k) => positional(ur[k]) === positional(ur[source]) && positional(lat[k]) === positional(lat[source]));
    if (!same) return draft();
    return { key, en: english, ur: positional(ur[source]), urLatn: positional(lat[source]), source: `host:${source}` };
  });
  const stale = Object.keys(DRAFT_WORDING).filter((k) => !rows.some((r) => r.key === k));
  if (stale.length) throw new Error(`draft wording for keys the screen no longer has: ${stale.join(', ')}`);
  return result;
}

const q = (text: string) => JSON.stringify(text);
export function renderTable(table: TranslationEntry[]): string {
  const lines = table.map((e) => `  { key: ${q(e.key)}, en: ${q(e.en)}, ur: ${q(e.ur)}, urLatn: ${q(e.urLatn)}, source: ${q(e.source)} },`);
  return `/**
 * @license
 * SPDX-License-Identifier: Apache-2.0
 */

// GENERATED by scripts/sdk-i18n/generate.ts - do not edit by hand.
// PENDING OWNER REVIEW. Every entry is complete (English, Urdu, Roman Urdu). \`source\` is \`host:<key>\` where the text is wording the Ijtema host
// already ships (reused only where the host's English is word-for-word the screen's), and \`draft\` where the SDK team wrote it
// (scripts/sdk-i18n/draft.ts). Neither is approved for production: a native speaker must review each string in its screen context.
export interface TranslationEntry {
  key: string;
  /** English; \`{0}\`, \`{1}\` stand for the arguments of a function-valued string. */
  en: string;
  ur: string;
  urLatn: string;
  /** \`host:<message key>\` or \`draft\`. */
  source: string;
}

export const TRANSLATION_TABLE: readonly TranslationEntry[] = [
${lines.join('\n')}
];
`;
}

export function renderReview(table: TranslationEntry[]): string {
  const host = table.filter((e) => e.source.startsWith('host:'));
  const draft = table.filter((e) => e.source === 'draft');
  const cell = (text: string) => text.replaceAll('|', '\\|');
  const rows = (entries: TranslationEntry[]) => entries.map((e) => `| \`${e.key}\` | ${cell(e.en)} | ${cell(e.ur)} | ${cell(e.urLatn)} | \`${e.source}\` |`).join('\n');
  return `# Urdu and Roman Urdu wording: complete drafts, pending native review

Status: **COMPLETE DRAFT. PENDING OWNER / NATIVE-SPEAKER REVIEW. Nothing here is approved for production.** Generated by \`scripts/sdk-i18n/generate.ts\`; do not edit by hand.

The SDK ships English only; the host supplies the screen's copy (see [LOCALIZATION_THEME_RTL.md](LOCALIZATION_THEME_RTL.md)). The reference app shows the
screen in English, Urdu (right to left) and Roman Urdu, and every one of the ${table.length} screen strings has all three wordings, so a developer can integrate and test
complete tables today. Two kinds of wording are in them:

- **Host-shipped (${host.length})**: text the Ijtema host app already ships, reused only where the host's English is word for word the screen's English.
- **Draft (${draft.length})**: written by the SDK team in \`scripts/sdk-i18n/draft.ts\` for strings the host has no equivalent for. Terminology follows the host's
  wording (لوکیشن / location, راستہ / rasta, منزل / manzil, رہنمائی / rehnumai, قدم / qadam, مقام / maqam for the venue, جگہ / jagah for a place).

Neither kind is a reviewed or approved translation. A native speaker must confirm each string in its screen context before any production release. Navigation-critical
wording to review first: \`liveBlockers.*\` (permission, approximate location, no GPS, stale or weak fix, outside the venue, outdated route), \`live.gpsWeak\`, \`live.gpsLost\`,
\`live.gpsRecovered\`, \`live.rerouting\`, \`live.rerouted\`, \`live.keptRoute\`, \`trip.errors.*\`, \`arrival.*\`, \`live.exit\`, \`trip.retry\`.

\`{0}\`, \`{1}\` are the values the screen fills in (a place name, a number, a distance); each draft keeps exactly the English placeholders. Automated checks
(\`src/__tests__/SdkTranslationTable.test.ts\`) cover missing and stale keys, empty text, placeholders, script (Urdu uses Arabic script, Roman Urdu Latin), and the
fallback to English for any key a table lacks.

## Host-shipped wording (${host.length})

| Key | English | Urdu | Roman Urdu | Source |
| --- | --- | --- | --- | --- |
${rows(host)}

## Draft wording written for the SDK screen (${draft.length})

| Key | English | Urdu | Roman Urdu | Source |
| --- | --- | --- | --- | --- |
${rows(draft)}
`;
}

if (process.argv[1] && process.argv[1].endsWith('generate.ts')) {
  const table = buildTable();
  const files: Array<[string, string]> = [[TABLE_FILE, renderTable(table)], [REVIEW_FILE, renderReview(table)]];
  if (process.argv.includes('--check')) {
    for (const [file, text] of files) if (readFileSync(file, 'utf8') !== text) { console.error(`${file} is out of date; run the generator`); process.exit(1); }
  } else {
    for (const [file, text] of files) writeFileSync(file, text);
    console.log(`${table.length} strings: ${table.filter((e) => e.source.startsWith('host:')).length} host wording, ${table.filter((e) => e.source === 'draft').length} draft`);
  }
}
