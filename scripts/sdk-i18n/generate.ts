// Builds the consumer's translation table from wording the Ijtema host ALREADY ships. A screen string gets an Urdu / Roman Urdu text only
// when the host has a message whose English is word-for-word the same; every other string stays English and is listed as missing. Nothing
// here translates anything. `node --import tsx scripts/sdk-i18n/generate.ts [--check]`; the committed output is
// `examples/expo-consumer/copy/translationTable.ts` and `docs/sdk/client/TRANSLATION_REVIEW.md`.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ENGLISH_NAVIGATION_SCREEN_COPY } from '../../packages/offline-navigation/src/ui/EnglishNavigationCopy';
import { messages } from '../../src/i18n/messages';

export interface TranslationEntry {
  /** Path into NavigationScreenCopy. */
  key: string;
  /** The SDK's English with `{0}`, `{1}` for the arguments of a function-valued string; null for a plain string. */
  en: string;
  ur?: string;
  urLatn?: string;
  /** Host message key the wording was taken from, absent when there is none. */
  source?: string;
}

const ROOT = join(__dirname, '../..');
const TABLE_FILE = join(ROOT, 'examples/expo-consumer/copy/translationTable.ts');
const REVIEW_FILE = join(ROOT, 'docs/sdk/client/TRANSLATION_REVIEW.md');
const en = messages.en as Record<string, string>;
const ur = messages.ur as Record<string, string>;
const lat = messages['ur-Latn'] as Record<string, string>;

const placeholders = (text: string): string[] => [...text.matchAll(/\{([a-zA-Z]+)\}/g)].map((m) => m[1]);
// Compared without placeholder names and case: `Step {step} of {total}` equals `Step {a} of {b}`.
const shape = (text: string): string => text.replace(/\{[a-zA-Z0-9]+\}/g, '{}').trim().toLowerCase();
const sample = (fn: (...args: string[]) => string): string => fn(...Array.from({ length: fn.length }, (_, i) => `{${i}}`));

const flatten = (node: unknown, path: string, out: Array<{ key: string; en: string }>) => {
  for (const [name, value] of Object.entries(node as Record<string, unknown>)) {
    const key = path ? `${path}.${name}` : name;
    if (typeof value === 'string') out.push({ key, en: value });
    else if (typeof value === 'function') out.push({ key, en: sample(value as (...args: string[]) => string) });
    else if (value && typeof value === 'object') flatten(value, key, out);
  }
};

export function buildTable(): TranslationEntry[] {
  const hostByShape = new Map<string, string[]>();
  for (const key of Object.keys(en)) {
    const s = shape(en[key]);
    hostByShape.set(s, [...(hostByShape.get(s) ?? []), key]);
  }
  const rows: Array<{ key: string; en: string }> = [];
  flatten(ENGLISH_NAVIGATION_SCREEN_COPY, '', rows);
  return rows.map(({ key, en: english }) => {
    // Only an unambiguous host wording qualifies: when several host messages share this English and their Urdu differs, the context decides
    // which is right, so the string is left for the owner instead of picking one.
    const candidates = hostByShape.get(shape(english))?.filter((k) => ur[k] && lat[k]) ?? [];
    const source = candidates[0];
    if (!source) return { key, en: english };
    // The host names its placeholders; the screen's functions take positional arguments in the same order of appearance.
    const names = placeholders(en[source]);
    const positional = (text: string) => text.replace(/\{([a-zA-Z]+)\}/g, (whole, name: string) => (names.includes(name) ? `{${names.indexOf(name)}}` : whole));
    const same = candidates.every((k) => positional(ur[k]) === positional(ur[source]) && positional(lat[k]) === positional(lat[source]));
    if (!same) return { key, en: english };
    return { key, en: english, ur: positional(ur[source]), urLatn: positional(lat[source]), source: `host:${source}` };
  });
}

const q = (text: string) => JSON.stringify(text);
export function renderTable(table: TranslationEntry[]): string {
  const lines = table.map((e) => `  { key: ${q(e.key)}, en: ${q(e.en)}${e.ur === undefined ? '' : `, ur: ${q(e.ur)}, urLatn: ${q(e.urLatn!)}, source: ${q(e.source!)}`} },`);
  return `/**
 * @license
 * SPDX-License-Identifier: Apache-2.0
 */

// GENERATED by scripts/sdk-i18n/generate.ts - do not edit by hand.
// PENDING OWNER REVIEW. Every Urdu / Roman Urdu text below is wording the Ijtema host already ships, reused only where the host's English is
// word-for-word the screen's English. Reuse is NOT approval for this screen's context. An entry with no \`ur\` has no reviewed wording and is
// shown in English. Nothing here was written or machine-translated by the SDK team.
export interface TranslationEntry {
  key: string;
  /** English; \`{0}\`, \`{1}\` stand for the arguments of a function-valued string. */
  en: string;
  ur?: string;
  urLatn?: string;
  source?: string;
}

export const TRANSLATION_TABLE: readonly TranslationEntry[] = [
${lines.join('\n')}
];
`;
}

export function renderReview(table: TranslationEntry[]): string {
  const have = table.filter((e) => e.ur !== undefined);
  const cell = (text: string | undefined) => (text === undefined ? '' : text.replaceAll('|', '\\|'));
  return `# Urdu and Roman Urdu wording: pending owner review

Status: **PENDING OWNER REVIEW. Nothing here is approved for production.** Generated by \`scripts/sdk-i18n/generate.ts\`; do not edit by hand.

The SDK ships English only. The sample app can show the screen in Urdu (right to left) and Roman Urdu to prove the layout. To avoid inventing
translations, a screen string gets Urdu / Roman Urdu text **only** where the Ijtema host already ships a message whose English is word for word the
same. Reusing a host string is not approval for this screen: the owner still has to confirm each one in its new context.

- Screen strings: ${table.length}
- With host-shipped wording (to review): ${have.length}
- With no wording yet (shown in English until the owner supplies it): ${table.length - have.length}

\`{0}\`, \`{1}\` are the values the screen fills in (a place name, a number, a distance).

## Host-shipped wording to review

| Key | English | Urdu | Roman Urdu | Host message |
| --- | --- | --- | --- | --- |
${have.map((e) => `| \`${e.key}\` | ${cell(e.en)} | ${cell(e.ur)} | ${cell(e.urLatn)} | \`${e.source}\` |`).join('\n')}

## Needs wording from the owner (shown in English today)

| Key | English |
| --- | --- |
${table.filter((e) => e.ur === undefined).map((e) => `| \`${e.key}\` | ${cell(e.en)} |`).join('\n')}
`;
}

if (process.argv[1] && process.argv[1].endsWith('generate.ts')) {
  const table = buildTable();
  const files: Array<[string, string]> = [[TABLE_FILE, renderTable(table)], [REVIEW_FILE, renderReview(table)]];
  if (process.argv.includes('--check')) {
    for (const [file, text] of files) if (readFileSync(file, 'utf8') !== text) { console.error(`${file} is out of date; run the generator`); process.exit(1); }
  } else {
    for (const [file, text] of files) writeFileSync(file, text);
    console.log(`${table.filter((e) => e.ur).length} of ${table.length} strings have host wording`);
  }
}
