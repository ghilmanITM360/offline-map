// Renders the map marker images (destination pin, start badge, user heading cone, gate badges, route chevron, facility badges) to PNG data URIs.
// Run after changing marker tokens or glyphs:  node scripts/offline-map/build-marker-images.mjs
// Dev-only (needs @resvg/resvg-js); the output is committed so builds and CI need no rasteriser.
// Glyphs are Lucide icons (ISC licence) read from node_modules/lucide-react-native.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { Resvg } from '@resvg/resvg-js';

const OUT = 'src/views/components/mapgl/markerImages.generated.ts';
const SCALE = 3; // images are authored in dp and rasterised at 3x (registered with scale 3)
const tokens = JSON.parse(readFileSync('src/theme/mapMarkerTokens.json', 'utf8'));

// Same mapping as the old FacilityLayer: Masjid -> landmark, id prefix -> glyph. (key -> lucide file)
export const FACILITY_GLYPHS = {
  landmark: 'landmark',
  food: 'utensils',
  water: 'droplet',
  medical: 'stethoscope',
  parking: 'circle-parking',
  bus: 'bus',
  lostfound: 'search',
  volunteer: 'circle-question-mark',
};

function lucideNodes(file) {
  const src = readFileSync(`node_modules/lucide-react-native/dist/esm/icons/${file}.js`, 'utf8');
  const m = /createLucideIcon\("[^"]+",\s*(\[[\s\S]*?\])\);/.exec(src);
  if (!m) throw new Error(`cannot read lucide icon ${file}`);
  return new Function(`return ${m[1]}`)();
}
const glyphSvg = (file, x, y, size, color) => {
  const els = lucideNodes(file)
    .map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).filter(([k]) => k !== 'key').map(([k, v]) => `${k}="${v}"`).join(' ')}/>`)
    .join('');
  return `<g transform="translate(${x} ${y}) scale(${size / 24})" fill="none" stroke="${color}" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${els}</g>`;
};

const svg = (w, h, body) => `<svg xmlns="http://www.w3.org/2000/svg" width="${w * SCALE}" height="${h * SCALE}" viewBox="0 0 ${w} ${h}">${body}</svg>`;

const images = {};
// Destination: teardrop pin, tip at the bottom centre (symbol anchor: bottom).
images['pin-destination'] = svg(36, 48, `<path d="M18 2C9.2 2 2 9.2 2 18c0 11.6 16 28 16 28s16-16.4 16-28C34 9.2 26.8 2 18 2z" fill="${tokens.destination}" stroke="#fff" stroke-width="2.5"/><circle cx="18" cy="18" r="6.5" fill="#fff"/>`);
// Start: filled badge with the navigation glyph.
images['pin-start'] = svg(28, 28, `<circle cx="14" cy="14" r="12" fill="${tokens.start}" stroke="#fff" stroke-width="2.5"/>${glyphSvg('navigation', 7.5, 7.5, 13, '#fff')}`);
// User heading cone: wedge pointing up from the centre of a transparent square, so the symbol can rotate about the dot.
images['user-heading'] = svg(88, 88, `<defs><radialGradient id="g" cx="44" cy="44" r="44" gradientUnits="userSpaceOnUse"><stop offset="0.18" stop-color="${tokens.user}" stop-opacity="0.6"/><stop offset="1" stop-color="${tokens.user}" stop-opacity="0"/></radialGradient></defs><path d="M44 44 L23 5.5 A44 44 0 0 1 65 5.5 Z" fill="url(#g)"/>`);
// Gate: badge with a door glyph (orange when its connector still needs field verification). The gate number is its label.
for (const [name, fill] of [['gate-badge', tokens.gate], ['gate-badge-warning', tokens.gateWarning]]) {
  images[name] = svg(32, 32, `<circle cx="16" cy="16" r="12.5" fill="${fill}" stroke="#fff" stroke-width="2.5"/>${glyphSvg('door-open', 9, 9, 14, '#fff')}`);
}
// Route direction: a small chevron pointing along the line (symbol-placement: line rotates it to the travel direction).
images['route-chevron'] = svg(16, 16, `<path d="M5 3.5 L11 8 L5 12.5" fill="none" stroke="#0B3D91" stroke-opacity="0.55" stroke-width="4.2" stroke-linecap="round" stroke-linejoin="round"/><path d="M5 3.5 L11 8 L5 12.5" fill="none" stroke="#fff" stroke-width="2.4" stroke-linecap="round" stroke-linejoin="round"/>`);
// Facility badges. The selected state is a ring LAYER drawn under the badge, not a second image per glyph: every image
// registered at map load delays the map becoming ready (16 images cost ~1.7 s on the emulator, 8 are deferred until after ready).
for (const [key, file] of Object.entries(FACILITY_GLYPHS)) {
  images[`facility-${key}`] = svg(32, 32, `<circle cx="16" cy="16" r="12" fill="${tokens.facility}" stroke="#fff" stroke-width="2"/>${glyphSvg(file, 9.5, 9.5, 13, '#fff')}`);
}

const entries = Object.entries(images).map(([name, s]) => {
  const png = new Resvg(s).render().asPng();
  return `  '${name}': { source: { uri: 'data:image/png;base64,${Buffer.from(png).toString('base64')}', scale: ${SCALE} } },`;
});
const body = entries.join('\n');
const hash = createHash('sha256').update(body).digest('hex').slice(0, 16);
writeFileSync(
  OUT,
  `/* eslint-disable */\n// GENERATED by scripts/offline-map/build-marker-images.mjs — do not edit. Content hash ${hash}.\n// Glyphs: Lucide (ISC). Colours: src/theme/mapMarkerTokens.json.\nexport const MARKER_IMAGES = {\n${body}\n} as const;\n\nexport type MarkerImageName = keyof typeof MARKER_IMAGES;\n`,
);
console.log(`wrote ${OUT}: ${Object.keys(images).length} images, ${(body.length / 1024).toFixed(0)} KB`);
